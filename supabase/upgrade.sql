create extension if not exists "pgcrypto";

-- Existing tables are extended, not dropped.
create table if not exists public.sailors (
  id bigint generated by default as identity primary key,
  name text not null,
  boat text not null default 'No boat',
  status text not null default 'Open to meet',
  location text not null,
  trip text,
  date text,
  skill text,
  latitude double precision not null,
  longitude double precision not null,
  created_at timestamp with time zone default now()
);

create table if not exists public.trips (
  id bigint generated by default as identity primary key,
  title text not null,
  route text not null,
  spots integer not null default 1 check (spots >= 0),
  date text not null,
  level text not null,
  host text not null,
  created_at timestamp with time zone default now()
);

create table if not exists public.forum_posts (
  id bigint generated by default as identity primary key,
  title text not null,
  replies integer not null default 0,
  tag text not null,
  author text not null,
  created_at timestamp with time zone default now()
);

alter table public.trips
add column if not exists description text default 'More details to be confirmed by the host.',
add column if not exists meeting_point text default 'To be confirmed',
add column if not exists cost_notes text default 'Costs to be agreed between skipper and crew.',
add column if not exists requirements text default 'To be confirmed',
add column if not exists city text default 'Copenhagen',
add column if not exists country text default 'Denmark',
add column if not exists region text default 'Europe',
add column if not exists latitude double precision default 55.6761,
add column if not exists longitude double precision default 12.5683,
add column if not exists is_location_approximate boolean default true,
add column if not exists owner_id uuid references auth.users(id) on delete set null,
add column if not exists updated_at timestamp with time zone default now();

alter table public.forum_posts
add column if not exists body text default '',
add column if not exists owner_id uuid references auth.users(id) on delete set null,
add column if not exists updated_at timestamp with time zone default now();

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  home_port text,
  region text default 'Europe',
  bio text,
  skill_level text default 'Beginner',
  verified boolean default false,
  show_approx_location boolean default true,
  latitude double precision,
  longitude double precision,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

create table if not exists public.boats (
  id bigint generated by default as identity primary key,
  owner_id uuid references auth.users(id) on delete cascade,
  name text not null,
  model text,
  length text,
  home_port text,
  description text,
  created_at timestamp with time zone default now()
);

create table if not exists public.trip_requests (
  id bigint generated by default as identity primary key,
  trip_id bigint references public.trips(id) on delete cascade,
  requester_id uuid references auth.users(id) on delete cascade,
  owner_id uuid references auth.users(id) on delete set null,
  name text not null,
  message text not null,
  status text default 'pending',
  created_at timestamp with time zone default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  trip_id bigint references public.trips(id) on delete cascade,
  sender_id uuid references auth.users(id) on delete cascade,
  receiver_id uuid references auth.users(id) on delete cascade,
  body text not null,
  read_at timestamp with time zone,
  created_at timestamp with time zone default now()
);

create table if not exists public.forum_comments (
  id bigint generated by default as identity primary key,
  post_id bigint references public.forum_posts(id) on delete cascade,
  author_id uuid references auth.users(id) on delete set null,
  author text not null,
  comment text not null,
  created_at timestamp with time zone default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  trip_id bigint references public.trips(id) on delete cascade,
  reviewer_id uuid references auth.users(id) on delete cascade,
  reviewed_user_id uuid references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text,
  created_at timestamp with time zone default now()
);

create table if not exists public.availability (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  start_date date not null,
  end_date date not null,
  region text default 'Europe',
  note text,
  created_at timestamp with time zone default now()
);

