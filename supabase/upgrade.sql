-- Authenticated creation/update
drop policy if exists "Users manage own profile" on public.profiles;
create policy "Users manage own profile" on public.profiles
for all using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Users manage own boats" on public.boats;
create policy "Users manage own boats" on public.boats
for all using (auth.uid() = owner_id) with check (auth.uid() = owner_id);

drop policy if exists "Authenticated create trips" on public.trips;
create policy "Authenticated create trips" on public.trips
for insert to authenticated with check (auth.uid() = owner_id);

drop policy if exists "Owners update own trips" on public.trips;
create policy "Owners update own trips" on public.trips
for update to authenticated using (auth.uid() = owner_id) with check (auth.uid() = owner_id);

drop policy if exists "Authenticated create forum posts" on public.forum_posts;
create policy "Authenticated create forum posts" on public.forum_posts
for insert to authenticated with check (auth.uid() = owner_id);

drop policy if exists "Owners update own forum posts" on public.forum_posts;
create policy "Owners update own forum posts" on public.forum_posts
for update to authenticated using (auth.uid() = owner_id) with check (auth.uid() = owner_id);

drop policy if exists "Authenticated create comments" on public.forum_comments;
create policy "Authenticated create comments" on public.forum_comments
for insert to authenticated with check (auth.uid() = author_id);

drop policy if exists "Authenticated create trip requests" on public.trip_requests;
create policy "Authenticated create trip requests" on public.trip_requests
for insert to authenticated with check (auth.uid() = requester_id);

drop policy if exists "Users read related trip requests" on public.trip_requests;
create policy "Users read related trip requests" on public.trip_requests
for select to authenticated using (auth.uid() = requester_id or auth.uid() = owner_id);

drop policy if exists "Users update owned trip requests" on public.trip_requests;
create policy "Users update owned trip requests" on public.trip_requests
for update to authenticated using (auth.uid() = owner_id) with check (auth.uid() = owner_id);

drop policy if exists "Users read own messages" on public.messages;
create policy "Users read own messages" on public.messages
for select to authenticated using (auth.uid() = sender_id or auth.uid() = receiver_id);

drop policy if exists "Users send messages" on public.messages;
create policy "Users send messages" on public.messages
for insert to authenticated with check (auth.uid() = sender_id);

drop policy if exists "Authenticated create reviews" on public.reviews;
create policy "Authenticated create reviews" on public.reviews
for insert to authenticated with check (auth.uid() = reviewer_id);

drop policy if exists "Users manage own availability" on public.availability;
create policy "Users manage own availability" on public.availability
for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

